package com.bank.model;

import java.math.BigDecimal;
import java.time.LocalDateTime;

/**
 * Account — mirrors the 'accounts' table.
 *
 * Folder in NetBeans:
 *   BankManagementSystem/src/com/bank/model/Account.java
 *
 * KEY TYPE DECISIONS:
 *   balance → BigDecimal   Never use double/float for money. BigDecimal is
 *                          exact and avoids rounding errors like $99.9999997.
 *   accountType → enum     Mirrors the MySQL ENUM('SAVINGS','CHECKING').
 *                          Prevents typos and makes switch-statements safe.
 *   status → enum          Mirrors the MySQL ENUM('ACTIVE','LOCKED','CLOSED').
 */
public class Account {

    // -------------------------------------------------------------------------
    // ENUMS  (mirror the MySQL ENUM columns exactly)
    // -------------------------------------------------------------------------

    public enum AccountType {
        SAVINGS, CHECKING;

        /** Parse a DB string safely, e.g. rs.getString("account_type"). */
        public static AccountType from(String value) {
            return AccountType.valueOf(value.toUpperCase());
        }
    }

    public enum AccountStatus {
        ACTIVE, LOCKED, CLOSED;

        public static AccountStatus from(String value) {
            return AccountStatus.valueOf(value.toUpperCase());
        }
    }

    /** Why a locked account is restricted; self-service recovery is only allowed for FAILED_PIN. */
    public enum LockReason {
        NONE, FAILED_PIN, ADMIN, BAN;

        public static LockReason from(String value) {
            return value == null || value.isBlank() ? NONE : LockReason.valueOf(value.toUpperCase());
        }
    }

    /** Why a closed account was closed; archive closures are restorable only by an administrator. */
    public enum ClosureReason {
        NONE, CUSTOMER_ARCHIVED, CUSTOMER_REQUEST, ADMIN_DECISION;

        public static ClosureReason from(String value) {
            return value == null || value.isBlank() ? NONE : ClosureReason.valueOf(value.toUpperCase());
        }
    }

    // -------------------------------------------------------------------------
    // FIELDS
    // -------------------------------------------------------------------------

    private long          accountId;

    /** FK to customers.customer_id */
    private long          customerId;

    private String        accountNumber;
    private String        cardNumber;

    /**
     * Stores the BCrypt / Argon2 hash — never the raw PIN.
     * The Java service layer will use a library (e.g. jBCrypt) to hash and
     * verify; this field just holds what comes back from the DB.
     */
    private String        pinHash;

    private AccountType   accountType;

    /** DECIMAL(18,2) → BigDecimal. Always use BigDecimal for money. */
    private BigDecimal    balance;

    private AccountStatus status;

    /** Explicit lock cause prevents PIN recovery from bypassing an administrator or ban lock. */
    private LockReason lockReason = LockReason.NONE;
    private ClosureReason closureReason = ClosureReason.NONE;

    /**
     * Tracks consecutive wrong PIN attempts.
     * Maps to the 'failed_pin_attempts' TINYINT column.
     * Reset to 0 on successful login; account is locked when it reaches 3.
     */
    private int failedPinAttempts;

    private LocalDateTime createdAt;

    // -------------------------------------------------------------------------
    // CONSTRUCTORS
    // -------------------------------------------------------------------------

    /** No-arg constructor — required by DAO result mappers. */
    public Account() {}

    /**
     * Full constructor — use when loading an existing row from the DB.
     */
    public Account(long accountId,
                   long customerId,
                   String accountNumber,
                   String cardNumber,
                   String pinHash,
                   AccountType accountType,
                   BigDecimal balance,
                   AccountStatus status,
                   LocalDateTime createdAt) {
        this.accountId     = accountId;
        this.customerId    = customerId;
        this.accountNumber = accountNumber;
        this.cardNumber    = cardNumber;
        this.pinHash       = pinHash;
        this.accountType   = accountType;
        this.balance       = balance;
        this.status        = status;
        this.createdAt     = createdAt;
    }

    /**
     * Insert constructor — use when creating a NEW account.
     * account_id and created_at are omitted (generated by MySQL).
     */
    public Account(long customerId,
                   String accountNumber,
                   String cardNumber,
                   String pinHash,
                   AccountType accountType,
                   BigDecimal balance) {
        this.customerId    = customerId;
        this.accountNumber = accountNumber;
        this.cardNumber    = cardNumber;
        this.pinHash       = pinHash;
        this.accountType   = accountType;
        this.balance       = balance;
        this.status        = AccountStatus.ACTIVE;  // new accounts start ACTIVE
    }

    // -------------------------------------------------------------------------
    // GETTERS & SETTERS
    // -------------------------------------------------------------------------

    public long getAccountId()                    { return accountId; }
    public void setAccountId(long accountId)      { this.accountId = accountId; }

    public long getCustomerId()                   { return customerId; }
    public void setCustomerId(long customerId)    { this.customerId = customerId; }

    public String getAccountNumber()              { return accountNumber; }
    public void setAccountNumber(String n)        { this.accountNumber = n; }

    public String getCardNumber()                 { return cardNumber; }
    public void setCardNumber(String cardNumber)  { this.cardNumber = cardNumber; }

    public String getPinHash()                    { return pinHash; }
    public void setPinHash(String pinHash)        { this.pinHash = pinHash; }

    public AccountType getAccountType()                  { return accountType; }
    public void setAccountType(AccountType accountType)  { this.accountType = accountType; }

    public BigDecimal getBalance()                { return balance; }
    public void setBalance(BigDecimal balance)    { this.balance = balance; }

    public AccountStatus getStatus()                  { return status; }
    public void setStatus(AccountStatus status)       { this.status = status; }

    public LockReason getLockReason()                 { return lockReason; }
    public void setLockReason(LockReason lockReason)  { this.lockReason = lockReason == null ? LockReason.NONE : lockReason; }
    public ClosureReason getClosureReason() { return closureReason; }
    public void setClosureReason(ClosureReason closureReason) {
        this.closureReason = closureReason == null ? ClosureReason.NONE : closureReason;
    }

    public int getFailedPinAttempts()                        { return failedPinAttempts; }
    public void setFailedPinAttempts(int failedPinAttempts)  { this.failedPinAttempts = failedPinAttempts; }

    public LocalDateTime getCreatedAt()               { return createdAt; }
    public void setCreatedAt(LocalDateTime createdAt) { this.createdAt = createdAt; }

    // -------------------------------------------------------------------------
    // UTILITY
    // -------------------------------------------------------------------------

    /** Quick status checks — useful in the Service and View layers. */
    public boolean isActive() { return status == AccountStatus.ACTIVE; }
    public boolean isLocked() { return status == AccountStatus.LOCKED; }
    public boolean isClosed() { return status == AccountStatus.CLOSED; }

    @Override
    public String toString() {
        return "Account{"
                + "accountId=" + accountId
                + ", accountNumber='" + accountNumber + '\''
                + ", type=" + accountType
                + ", balance=" + balance
                + ", status=" + status
                + '}';
    }
}