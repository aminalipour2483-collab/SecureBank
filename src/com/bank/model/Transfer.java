package com.bank.model;

import java.math.BigDecimal;
import java.time.LocalDateTime;

/**
 * Transfer — mirrors the 'transfers' table.
 *
 * Folder in NetBeans:
 *   BankManagementSystem/src/com/bank/model/Transfer.java
 *
 * A Transfer record links the two Transaction rows that are created whenever
 * money moves between accounts:
 *
 *   transfers table
 *       sender_account_id  ──► transactions row (TRANSFER_OUT)
 *       receiver_account_id ──► transactions row (TRANSFER_IN)
 *
 * The reference_number is what gets printed on receipts and used for
 * customer support lookups.
 */
public class Transfer {

    // -------------------------------------------------------------------------
    // ENUM  (mirrors MySQL ENUM column exactly)
    // -------------------------------------------------------------------------

    public enum TransferStatus {
        PENDING,
        COMPLETED,
        FAILED,
        REVERSED;

        public static TransferStatus from(String value) {
            return TransferStatus.valueOf(value.toUpperCase());
        }
    }

    // -------------------------------------------------------------------------
    // FIELDS
    // -------------------------------------------------------------------------

    private long           transferId;

    /** FK to accounts.account_id — the account money leaves. */
    private long           senderAccountId;

    /** FK to accounts.account_id — the account money arrives in. */
    private long           receiverAccountId;

    private BigDecimal     amount;

    /**
     * Unique human-readable reference, e.g. "TXF-2024-03-01-0001".
     * UUID format also works. Generated by the Service layer before INSERT.
     */
    private String         referenceNumber;

    private TransferStatus status;

    private LocalDateTime  createdAt;

    // -------------------------------------------------------------------------
    // CONSTRUCTORS
    // -------------------------------------------------------------------------

    /** No-arg constructor — required by DAO result mappers. */
    public Transfer() {}

    /**
     * Full constructor — use when loading an existing row from the DB.
     */
    public Transfer(long transferId,
                    long senderAccountId,
                    long receiverAccountId,
                    BigDecimal amount,
                    String referenceNumber,
                    TransferStatus status,
                    LocalDateTime createdAt) {
        this.transferId         = transferId;
        this.senderAccountId    = senderAccountId;
        this.receiverAccountId  = receiverAccountId;
        this.amount             = amount;
        this.referenceNumber    = referenceNumber;
        this.status             = status;
        this.createdAt          = createdAt;
    }

    /**
     * Insert constructor — use when initiating a NEW transfer.
     * transfer_id and created_at are omitted (MySQL generates them).
     * Status defaults to PENDING — the Service layer updates it to
     * COMPLETED or FAILED after the transaction pair is written.
     */
    public Transfer(long senderAccountId,
                    long receiverAccountId,
                    BigDecimal amount,
                    String referenceNumber) {
        this.senderAccountId   = senderAccountId;
        this.receiverAccountId = receiverAccountId;
        this.amount            = amount;
        this.referenceNumber   = referenceNumber;
        this.status            = TransferStatus.PENDING;
    }

    // -------------------------------------------------------------------------
    // GETTERS & SETTERS
    // -------------------------------------------------------------------------

    public long getTransferId()                    { return transferId; }
    public void setTransferId(long transferId)     { this.transferId = transferId; }

    public long getSenderAccountId()               { return senderAccountId; }
    public void setSenderAccountId(long id)        { this.senderAccountId = id; }

    public long getReceiverAccountId()             { return receiverAccountId; }
    public void setReceiverAccountId(long id)      { this.receiverAccountId = id; }

    public BigDecimal getAmount()                  { return amount; }
    public void setAmount(BigDecimal amount)       { this.amount = amount; }

    public String getReferenceNumber()             { return referenceNumber; }
    public void setReferenceNumber(String ref)     { this.referenceNumber = ref; }

    public TransferStatus getStatus()                  { return status; }
    public void setStatus(TransferStatus status)       { this.status = status; }

    public LocalDateTime getCreatedAt()                    { return createdAt; }
    public void setCreatedAt(LocalDateTime createdAt)      { this.createdAt = createdAt; }

    // -------------------------------------------------------------------------
    // UTILITY
    // -------------------------------------------------------------------------

    public boolean isPending()   { return status == TransferStatus.PENDING; }
    public boolean isCompleted() { return status == TransferStatus.COMPLETED; }
    public boolean isFailed()    { return status == TransferStatus.FAILED; }
    public boolean isReversed()  { return status == TransferStatus.REVERSED; }

    @Override
    public String toString() {
        return "Transfer{"
                + "transferId=" + transferId
                + ", from=" + senderAccountId
                + ", to=" + receiverAccountId
                + ", amount=" + amount
                + ", ref='" + referenceNumber + '\''
                + ", status=" + status
                + '}';
    }
}